/*
 * An Android app in Jetpack Compose. Its logic comes from a Kotlin
 * Multiplatform library; the app holds the UI and the platform adapters.
 *
 * Tests run on the JVM with Robolectric, inside `check`: no emulator needed.
 * They run on the JUnit platform; JUnit 4 is only the API Robolectric needs.
 * Lint warnings and uncovered code fail the build, as on the other projects.
 */
import com.android.build.api.dsl.ApplicationExtension
import com.android.build.api.variant.ApplicationAndroidComponentsExtension
import com.android.build.api.variant.HasHostTestsBuilder
import com.android.build.api.variant.HostTestBuilder

plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.plugin.compose")
    id("org.jetbrains.kotlinx.kover")
    id("com.diffplug.spotless")
}

group = "dev.ylp"

// AGP 9 generates no `android` accessor for precompiled plugins: configure it by type.
extensions.configure<ApplicationExtension> {
    compileSdk = providers.gradleProperty("androidCompileSdk").get().toInt()

    defaultConfig {
        minSdk = providers.gradleProperty("androidMinSdk").get().toInt()
        targetSdk = providers.gradleProperty("androidTargetSdk").get().toInt()
        versionCode = 1
        versionName = providers.gradleProperty("version").getOrElse("0.0.0")
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    lint {
        warningsAsErrors = true
        abortOnError = true
        // A newer dependency is Renovate's job, not a reason to fail a pull request.
        disable += setOf("GradleDependency", "NewerVersionAvailable", "AndroidGradlePluginVersion")
    }

    testOptions {
        unitTests {
            // Robolectric reads the merged manifest and resources.
            isIncludeAndroidResources = true
            all {
                it.useJUnitPlatform()
                // Robolectric reaches JDK internals that recent JDKs no longer export by default.
                it.jvmArgs("--add-exports=java.base/jdk.internal.access=ALL-UNNAMED")
            }
        }
    }
}

val libs = the<VersionCatalogsExtension>().named("libs")

fun library(alias: String) = libs.findLibrary(alias).get()

// The JUnit platform runs every test: Jupiter for plain JVM tests, Vintage for the JUnit 4 API
// that Robolectric and the Compose test rule still require.
dependencies {
    // Compose versions aligned by its BOM; the compiler plugin needs the runtime that ui brings.
    "implementation"(platform(library("compose-bom")))
    "implementation"(library("compose-ui"))
    "testImplementation"(platform(library("compose-bom")))
    "testImplementation"(platform(library("junit-bom")))
    "testImplementation"(library("junit-jupiter"))
    "testImplementation"(library("junit4"))
    "testRuntimeOnly"(library("junit-vintage-engine"))
    "testRuntimeOnly"(library("junit-platform-launcher"))
}

// The JVM tests run once, on the debug variant: the release variant only differs by its signing.
extensions.configure<ApplicationAndroidComponentsExtension> {
    beforeVariants(selector().withBuildType("release")) { variant ->
        (variant as HasHostTestsBuilder).hostTests[HostTestBuilder.UNIT_TEST_TYPE]?.enable = false
    }
}

kover {
    reports {
        filters {
            excludes {
                // Generated by the build and the Compose compiler.
                classes("*.BuildConfig", "*.R", "*.R$*", "*.ComposableSingletons*")
            }
        }
        variant("debug") {
            verify {
                rule {
                    bound { minValue = 80 }
                    bound {
                        minValue = 80
                        coverageUnits = kotlinx.kover.gradle.plugin.dsl.CoverageUnit.BRANCH
                    }
                }
            }
        }
    }
}

tasks.named("check") {
    dependsOn("koverVerifyDebug")
}

spotless {
    kotlin {
        target("src/**/*.kt")
        // Composable functions are named like types, as Compose requires.
        ktlint().editorConfigOverride(mapOf("ktlint_function_naming_ignore_when_annotated_with" to "Composable"))
    }
    kotlinGradle {
        target("*.gradle.kts")
        ktlint()
    }
}
