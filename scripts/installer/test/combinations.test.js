// Every combination of clients, generated in memory from the template itself: the blocks are
// paired, and what a project keeps never points at what it left out.
import { execFileSync } from 'node:child_process';
import { readFileSync, statSync } from 'node:fs';
import { dirname, join, normalize } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { CLIENTS } from '../src/clients.js';
import { PROVENANCE_PATH, transformTree } from '../src/transform.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');

/** The template's tracked files, as the installer reads them. */
const template = new Map(
  execFileSync('git', ['ls-files', '-z'], { cwd: root, encoding: 'utf8' })
    .split('\0')
    .filter(Boolean)
    .filter((path) => statSync(join(root, path), { throwIfNoEntry: false })?.isFile())
    .map((path) => [path, { content: readFileSync(join(root, path)), mode: 0o644 }]),
);

/** @type {import('../src/clients.js').Client[][]} */
const combinations = [];
for (let mask = 1; mask < 1 << CLIENTS.length; mask++) {
  combinations.push(CLIENTS.filter((_, index) => mask & (1 << index)));
}

/** What a kept file must not name once a marker name does not hold. */
const TRACES = {
  web: ['apps/services/api-app', ':apps:services:api-app', 'use-the-web-app.md', 'frontend-convention'],
  mobile: [
    'apps/clients/android',
    'apps/clients/ios',
    ':apps:clients:android',
    'android.yml',
    'ios.yml',
    'the-android-app.md',
    'the-ios-app.md',
    'xcode-app',
    'android-app-convention',
  ],
  cli: ['apps/clients/cli', ':apps:clients:cli', 'cli.yml', 'the-cli.md', 'kotlin-native-cli-convention'],
  native: ['apps/clients/shared', ':apps:clients:shared', 'clients.md', 'kotlin-multiplatform-convention', 'openapi-kotlin-client'],
};

/** @param {Set<string>} clients */
const absent = (clients) =>
  Object.keys(TRACES).filter((name) =>
    name === 'native' ? !clients.has('cli') && !clients.has('mobile') : !clients.has(name),
  );

describe.each(combinations.map((clients) => [clients.join(','), clients]))('the clients %s', (_, list) => {
  const clients = new Set(list);
  const answers = { name: 'demo-app', owner: 'example', packageName: 'dev.example.demo', clientId: 'demo-app-web', clients };
  const project = transformTree(template, answers);
  project.set(PROVENANCE_PATH, { content: new TextEncoder().encode('# Template\n'), mode: 0o644 });
  const decoder = new TextDecoder();
  const texts = [...project]
    .filter(([, file]) => !file.content.subarray(0, 8000).includes(0))
    .map(([path, file]) => /** @type {[string, string]} */ ([path, decoder.decode(file.content)]));

  it('keeps no trace of the clients it left out', () => {
    const traces = absent(clients).flatMap((name) => TRACES[/** @type {keyof typeof TRACES} */ (name)]);
    const found = texts.flatMap(([path, text]) =>
      traces.filter((trace) => text.includes(trace)).map((trace) => `${path}: ${trace}`),
    );
    expect(found).toEqual([]);
  });

  it('links only to pages it has', () => {
    // The domain model page is generated by the build; GitHub resolves .github's links from the root.
    const generated = new Set(['docs/architecture/domain-model.md']);
    const broken = texts
      .filter(([path]) => path.endsWith('.md') && !path.startsWith('.github/'))
      .flatMap(([path, text]) =>
        [...text.matchAll(/\]\((?!https?:|#|mailto:)([^)\s#]+)/g)]
          .map((match) => normalize(join(dirname(path), match[1])))
          .filter((target) => !generated.has(target) && !project.has(target) && ![...project.keys()].some((key) => key.startsWith(`${target}/`)))
          .map((target) => `${path} -> ${target}`),
      );
    expect(broken).toEqual([]);
  });

  it('includes only the Gradle projects it has', () => {
    const settings = texts.find(([path]) => path === 'settings.gradle.kts')?.[1] ?? '';
    const missing = [...settings.matchAll(/include\("([^"]+)"\)/g)]
      .map((match) => match[1].replaceAll(':', '/'))
      .filter((dir) => !project.has(`${dir}/build.gradle.kts`));
    expect(missing).toEqual([]);
  });

  it('calls only the workflows it has', () => {
    const missing = texts
      .filter(([path]) => path.startsWith('.github/workflows/'))
      .flatMap(([, text]) => [...text.matchAll(/uses: \.\/(\.github\/workflows\/[^\s]+)/g)].map((match) => match[1]))
      .filter((workflow) => !project.has(workflow));
    expect(missing).toEqual([]);
  });
});
